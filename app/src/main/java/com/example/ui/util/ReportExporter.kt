package com.example.ui.util

import android.content.Context
import android.content.Intent
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import androidx.core.content.FileProvider
import com.example.data.local.entities.MessEntity
import com.example.domain.model.MessCalculationSummary
import java.io.File
import java.io.FileOutputStream

object ReportExporter {

    fun exportAndShareCsv(
        context: Context,
        mess: MessEntity?,
        summary: MessCalculationSummary
    ) {
        val fileName = "meal_summary_${summary.month}.csv"
        val file = File(context.cacheDir, fileName)

        val csvContent = buildString {
            appendLine("Mess Name,${mess?.name ?: "Meal Manager"}")
            appendLine("Month,${summary.month}")
            appendLine("Total Bazar Cost,${summary.totalBazarCost}")
            appendLine("Total Meals,${summary.totalMeals}")
            appendLine("Meal Rate,${String.format(java.util.Locale.US, "%.2f", summary.mealRate)}")
            appendLine("Total Fixed Costs,${summary.totalFixedCosts}")
            appendLine("Total Deposits,${summary.totalDeposits}")
            appendLine()
            appendLine("Member Name,Role,Status,Breakfast,Lunch,Dinner,Guest,Total Meals,Meal Cost,Fixed Cost Share,Opening Balance,Total Deposits,Total Cost,Net Balance")
            summary.memberCalculations.forEach { m ->
                appendLine("\"${m.name}\",${m.role},${m.type},${m.totalBreakfast},${m.totalLunch},${m.totalDinner},${m.totalGuestMeals},${m.totalMeals},${m.mealCost},${m.fixedCostShare},${m.openingBalance},${m.totalDeposits},${m.totalCost},${m.netBalance}")
            }
        }

        FileOutputStream(file).use { it.write(csvContent.toByteArray(Charsets.UTF_8)) }

        val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)
        val shareIntent = Intent(Intent.ACTION_SEND).apply {
            type = "text/csv"
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_SUBJECT, "Meal Summary CSV - ${summary.month}")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        context.startActivity(Intent.createChooser(shareIntent, "Share CSV Statement"))
    }

    fun exportAndSharePdf(
        context: Context,
        mess: MessEntity?,
        summary: MessCalculationSummary
    ) {
        val fileName = "meal_statement_${summary.month}.pdf"
        val file = File(context.cacheDir, fileName)

        val pdfDocument = PdfDocument()
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create() // Standard A4 portrait
        val page = pdfDocument.startPage(pageInfo)
        val canvas = page.canvas

        val titlePaint = Paint().apply {
            color = Color.rgb(15, 118, 110)
            textSize = 20f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val subPaint = Paint().apply {
            color = Color.DKGRAY
            textSize = 11f
        }
        val boldPaint = Paint().apply {
            color = Color.BLACK
            textSize = 10f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val textPaint = Paint().apply {
            color = Color.BLACK
            textSize = 10f
        }
        val linePaint = Paint().apply {
            color = Color.LTGRAY
            strokeWidth = 1f
        }
        val greenPaint = Paint().apply {
            color = Color.rgb(22, 163, 74)
            textSize = 10f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }
        val redPaint = Paint().apply {
            color = Color.rgb(220, 38, 38)
            textSize = 10f
            typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        }

        var y = 40f
        canvas.drawText(mess?.name ?: "Meal Manager Statement", 30f, y, titlePaint)
        y += 18f
        canvas.drawText("Monthly Statement: ${summary.month}  |  Generated by Meal Manager", 30f, y, subPaint)
        y += 14f
        canvas.drawLine(30f, y, 565f, y, linePaint)
        y += 18f

        // Overview Box
        canvas.drawText("Total Bazar: ৳${String.format(java.util.Locale.US, "%.2f", summary.totalBazarCost)}", 30f, y, boldPaint)
        canvas.drawText("Total Meals: ${summary.totalMeals}", 200f, y, boldPaint)
        canvas.drawText("Meal Rate: ৳${String.format(java.util.Locale.US, "%.2f", summary.mealRate)}", 350f, y, boldPaint)
        y += 16f
        canvas.drawText("Fixed Costs: ৳${String.format(java.util.Locale.US, "%.2f", summary.totalFixedCosts)}", 30f, y, boldPaint)
        canvas.drawText("Total Deposits: ৳${String.format(java.util.Locale.US, "%.2f", summary.totalDeposits)}", 200f, y, boldPaint)
        y += 16f
        canvas.drawLine(30f, y, 565f, y, linePaint)
        y += 20f

        // Table Header
        canvas.drawText("Member Name", 30f, y, boldPaint)
        canvas.drawText("Meals", 180f, y, boldPaint)
        canvas.drawText("Meal Cost", 240f, y, boldPaint)
        canvas.drawText("Fixed", 320f, y, boldPaint)
        canvas.drawText("Deposit", 380f, y, boldPaint)
        canvas.drawText("Net Balance", 460f, y, boldPaint)
        y += 10f
        canvas.drawLine(30f, y, 565f, y, linePaint)
        y += 16f

        // Rows
        summary.memberCalculations.forEach { m ->
            canvas.drawText(m.name.take(22), 30f, y, textPaint)
            canvas.drawText("${m.totalMeals}", 180f, y, textPaint)
            canvas.drawText("৳${String.format(java.util.Locale.US, "%.1f", m.mealCost)}", 240f, y, textPaint)
            canvas.drawText("৳${String.format(java.util.Locale.US, "%.1f", m.fixedCostShare)}", 320f, y, textPaint)
            canvas.drawText("৳${String.format(java.util.Locale.US, "%.1f", m.totalDeposits)}", 380f, y, textPaint)

            val isPositive = m.netBalance >= 0
            val balText = (if (isPositive) "+৳" else "-৳") + String.format(java.util.Locale.US, "%.2f", kotlin.math.abs(m.netBalance))
            canvas.drawText(balText, 460f, y, if (isPositive) greenPaint else redPaint)

            y += 18f
            if (y > 800f) return@forEach // Single-page cap for standard report slip
        }

        y += 10f
        canvas.drawLine(30f, y, 565f, y, linePaint)
        y += 20f
        canvas.drawText("* Positive (+) balance indicates refund receivable. Negative (-) balance indicates due payable.", 30f, y, subPaint)

        pdfDocument.finishPage(page)

        FileOutputStream(file).use { pdfDocument.writeTo(it) }
        pdfDocument.close()

        val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", file)
        val shareIntent = Intent(Intent.ACTION_SEND).apply {
            type = "application/pdf"
            putExtra(Intent.EXTRA_STREAM, uri)
            putExtra(Intent.EXTRA_SUBJECT, "Meal Statement PDF - ${summary.month}")
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        context.startActivity(Intent.createChooser(shareIntent, "Share PDF Statement"))
    }
}
